'use strict';

/**
 * Builds a draft Delegation Charter (SPEC.md §Machine-readable form) for one
 * agent from what the diagnosis could infer. Everything inferred is marked in
 * `_diagnostic.inferred`; everything a person must write is null and listed in
 * `_diagnostic.to_write`. State is always "draft": a charter only becomes
 * Active when its owner (and, where required, an approver) says so.
 */

const SPEC = 'delegation-charter/0.1.1';

function draftCharter(r, { now }) {
  const toWrite = [];
  const inferred = [];
  const need = (field, why) => toWrite.push({ field, why });

  const purpose = (r.header.find((h) => h.key === 'purpose') || {}).status === 'stated' ? (r.header.find((h) => h.key === 'purpose').evidence || '').replace(/^“|”$/g, '') : null;
  if (purpose) inferred.push({ field: 'purpose', from: 'agent instructions or description' });
  else need('purpose', 'MUST: the business goal, in one or two sentences.');

  const approvalRequired = r.activation.path === 'approval';
  const neverDo = r.never_do_stated.map((item) => ({ item, enforcement: 'instructed' }));
  if (neverDo.length) inferred.push({ field: 'scope.never_do', from: 'prohibitions found in instructions; each is Instructed until tied to a tool' });
  need('scope.never_do', neverDo.length ? 'Review the items found; add specific, testable items and tie those you can to a tool (Enforced).' : 'MUST NOT be empty.');

  const systems = r.tools.map((t) => ({ tool: t.key, access: t.wildcard ? 'unknown' : t.access }));
  if (systems.length) inferred.push({ field: 'systems[].access', from: 'tool names and OpenAPI methods; confirm each' });
  if (r.tools.some((t) => t.wildcard)) need('systems', 'Replace whole-server MCP grants with the named tools the agent needs.');

  if (!r.author.exists) need('owner', 'The creator no longer exists; name the person who answers for this agent.');
  else inferred.push({ field: 'owner', from: 'agent creator; confirm they are accountable' });
  need('escalation_recipient', 'MUST: who receives work the agent must not finish.');
  if (approvalRequired) need('approval_authority', 'MUST: the agent is shared or holds write or irreversible tools.');

  const rules = [
    { trigger: 'out_of_scope', action: null, to: null },
    { trigger: 'never_do_match', action: 'hand_off', to: 'escalation_recipient' },
    { trigger: 'missing_required_input', action: 'ask_requester' },
    { trigger: 'irreversible_action', action: 'hold_for_approval', to: approvalRequired ? 'approval_authority' : 'owner' },
  ];
  need('escalation_rules[out_of_scope]', 'Choose: hand_off, ask_requester, draft_only, or notify_and_continue.');
  inferred.push({ field: 'escalation_rules', from: 'spec defaults for triggers 2 to 4; confirm' });

  return {
    spec: SPEC,
    id: `chr_${r.id}`,
    version: 0,
    name: r.name,
    description: null,
    purpose,
    success_measure: null,
    review_date: null,
    state: 'draft',
    activation: null,
    owner: { identity: r.author.exists ? `user:${r.author.id}` : null },
    escalation_recipient: { identity: null, backup: null },
    approval_authority: { identity: null },
    scope: { will_do: [], never_do: neverDo },
    systems,
    inputs: { required: [], optional: [] },
    outputs: [],
    escalation_rules: rules,
    constraints: {
      irreversible_actions: 'require_approval',
      max_tool_calls_per_run: null,
      background_runs: r.schedules > 0,
      retention_days: null,
    },
    _diagnostic: {
      generated_at: now,
      agent_id: r.id,
      approval_required: approvalRequired,
      inferred,
      to_write: toWrite,
      note: 'Generated by librechat-charter-diagnostic. Not a charter until its owner completes and activates it.',
    },
  };
}

module.exports = { draftCharter, SPEC };
